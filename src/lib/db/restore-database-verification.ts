/**
 * Safe, aggregate-only verification of a plain PostgreSQL dump.
 *
 * The verifier deliberately keeps the source and restore connection strings in memory only.
 * `psql` receives the generated database name as an argument and credentials through libpq
 * environment variables, so a process listing never contains a production password. No row
 * values are returned or written to the report: each column is represented by a sorted digest of
 * its textual values, with an explicit null marker.
 */
import { spawn } from "node:child_process";
import { closeSync, existsSync, fsyncSync, mkdirSync, openSync, readSync, renameSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { randomBytes } from "node:crypto";
import { Client, type QueryResultRow } from "pg";
import { postgresToolEnv } from "./postgres-connection-env";

const DEFAULT_COMMAND_TIMEOUT_MS = 10 * 60 * 1000;
const CONNECTION_TIMEOUT_MS = 20_000;
const QUERY_TIMEOUT_MS = 10 * 60 * 1000;
const MAX_DUMP_BYTES = 20 * 1024 * 1024 * 1024;
const PUBLIC_SCHEMA = "public";
const MIGRATION_TABLE = "_prisma_migrations";

export interface RestoreVerificationOptions {
  dumpPath: string;
  sourceUrl: string;
  targetTemplateUrl: string;
  psqlPath?: string;
  allowSameServer?: boolean;
  commandTimeoutMs?: number;
}

export interface ColumnAggregate {
  rowCount: string;
  checksum: string;
}

export interface TableAggregate {
  rowCount: string;
  columns: Record<string, ColumnAggregate>;
  schema: Array<{
    name: string;
    ordinal: number;
    dataType: string;
    udtName: string;
  }>;
}

export interface DatabaseAggregate {
  totalRows: string;
  tables: Record<string, TableAggregate>;
}

export interface RestoreVerificationReport {
  status: "PASS" | "FAIL";
  startedAt: string;
  finishedAt: string;
  durationMs: number;
  source: string;
  target: string;
  dump: { path: string; sizeBytes: number };
  sourceAggregate?: DatabaseAggregate;
  restoredAggregate?: DatabaseAggregate;
  mismatches: string[];
  cleanup: "PASS" | "FAIL";
  error?: string;
}

class RestoreVerificationError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "RestoreVerificationError";
  }
}

interface DatabaseUrlInfo {
  url: URL;
  database: string;
  host: string;
  port: string;
}

interface ColumnRow extends QueryResultRow {
  table_name: string;
  column_name: string;
  ordinal_position: number;
  data_type: string;
  udt_name: string;
}

interface AggregateRow extends QueryResultRow {
  __row_count: string;
  [column: string]: string;
}

function parseDatabaseUrl(raw: string, label: string): DatabaseUrlInfo {
  let url: URL;
  try {
    url = new URL(raw);
  } catch {
    throw new RestoreVerificationError(`${label} is not a valid PostgreSQL URL.`);
  }
  if (url.protocol !== "postgres:" && url.protocol !== "postgresql:") {
    throw new RestoreVerificationError(`${label} must use postgresql://.`);
  }
  const database = decodeURIComponent(url.pathname.replace(/^\//, ""));
  if (!database) throw new RestoreVerificationError(`${label} is missing a database name.`);
  return {
    url,
    database,
    host: url.hostname.toLowerCase(),
    port: url.port || "5432",
  };
}

function withDatabase(info: DatabaseUrlInfo, database: string): string {
  const url = new URL(info.url.toString());
  url.pathname = `/${encodeURIComponent(database)}`;
  return url.toString();
}

function describeDatabase(info: DatabaseUrlInfo): string {
  return `${info.host}:${info.port}/${info.database}`;
}

function quoteIdentifier(identifier: string): string {
  return `"${identifier.replaceAll('"', '""')}"`;
}

function assertDump(dumpPath: string): { absolutePath: string; sizeBytes: number } {
  const absolutePath = path.resolve(dumpPath);
  if (!existsSync(absolutePath)) {
    throw new RestoreVerificationError(`Dump file does not exist: ${path.basename(absolutePath)}.`);
  }
  const stats = statSync(absolutePath);
  if (!stats.isFile() || stats.size <= 0 || stats.size > MAX_DUMP_BYTES) {
    throw new RestoreVerificationError("Dump file is empty, not a regular file, or exceeds the safety limit.");
  }
  // A plain dump generated by pg_dump has this trailer. A missing trailer is not proof that the
  // file is unusable, but accepting it would make a truncated copy look like a valid backup.
  const fd = openSync(absolutePath, "r");
  const tailBytes = Buffer.alloc(Math.min(512, stats.size));
  try {
    readSync(fd, tailBytes, 0, tailBytes.length, Math.max(0, stats.size - tailBytes.length));
  } finally {
    closeSync(fd);
  }
  const tail = tailBytes.toString("utf8");
  if (!/PostgreSQL database dump complete\.?/i.test(tail)) {
    throw new RestoreVerificationError("Dump is missing the PostgreSQL completion trailer; it may be truncated.");
  }
  return { absolutePath, sizeBytes: stats.size };
}

function createClient(databaseUrl: string): Client {
  const parsed = new URL(databaseUrl);
  const sslmode = parsed.searchParams.get("sslmode")?.toLowerCase();
  // Remove the URL option when supplying an explicit pg SSL object. pg's connection-string
  // parser otherwise overwrites `rejectUnauthorized: false` after parsing `sslmode=require`.
  const connectionString =
    sslmode === "require"
      ? (() => {
          parsed.searchParams.delete("sslmode");
          return parsed.toString();
        })()
      : databaseUrl;
  return new Client({
    connectionString,
    // pg 8.22 currently aliases `sslmode=require` to `verify-full`, unlike libpq and psql.
    // Railway's public proxy presents a private chain, so preserve the requested encrypted
    // transport semantics without silently upgrading it to CA/hostname verification. An
    // explicitly requested `verify-full` remains strict.
    ...(sslmode === "require" ? { ssl: { rejectUnauthorized: false } } : {}),
    connectionTimeoutMillis: CONNECTION_TIMEOUT_MS,
    query_timeout: QUERY_TIMEOUT_MS,
    statement_timeout: QUERY_TIMEOUT_MS,
    keepAlive: true,
  });
}

async function closeClient(client: Client | undefined): Promise<void> {
  if (!client) return;
  try {
    await client.end();
  } catch {
    // Cleanup is reported by the caller; never hide the primary verification failure here.
  }
}

async function connectAdmin(target: DatabaseUrlInfo): Promise<{ client: Client; url: string }> {
  const candidates = ["postgres", target.database].filter(
    (database, index, values) => values.indexOf(database) === index,
  );
  for (const database of candidates) {
    const url = withDatabase(target, database);
    const client = createClient(url);
    try {
      await client.connect();
      await client.query("SELECT 1");
      return { client, url };
    } catch (error) {
      await closeClient(client);
    }
  }
  throw new RestoreVerificationError(
    `Could not connect to the target PostgreSQL administration database (${target.host}:${target.port}).`,
  );
}

async function createDisposableDatabase(target: DatabaseUrlInfo, database: string): Promise<string> {
  const admin = await connectAdmin(target);
  try {
    await admin.client.query(`CREATE DATABASE ${quoteIdentifier(database)}`);
    return admin.url;
  } catch (error) {
    throw new RestoreVerificationError("Could not create the disposable restore database.");
  } finally {
    await closeClient(admin.client);
  }
}

async function dropDisposableDatabase(target: DatabaseUrlInfo, database: string): Promise<void> {
  const admin = await connectAdmin(target);
  try {
    await admin.client.query(`DROP DATABASE IF EXISTS ${quoteIdentifier(database)}`);
  } catch {
    throw new RestoreVerificationError("Could not remove the disposable restore database.");
  } finally {
    await closeClient(admin.client);
  }
}

async function listColumns(client: Client): Promise<Map<string, TableAggregate["schema"]>> {
  const result = await client.query<ColumnRow>(
    `
      SELECT c.table_name, c.column_name, c.ordinal_position, c.data_type, c.udt_name
      FROM information_schema.columns AS c
      INNER JOIN information_schema.tables AS t
        ON t.table_schema = c.table_schema AND t.table_name = c.table_name
      WHERE c.table_schema = $1
        AND c.table_name <> $2
        AND t.table_type = 'BASE TABLE'
      ORDER BY c.table_name, c.ordinal_position
    `,
    [PUBLIC_SCHEMA, MIGRATION_TABLE],
  );
  const tables = new Map<string, TableAggregate["schema"]>();
  for (const row of result.rows) {
    const columns = tables.get(row.table_name) ?? [];
    columns.push({
      name: row.column_name,
      ordinal: Number(row.ordinal_position),
      dataType: row.data_type,
      udtName: row.udt_name,
    });
    tables.set(row.table_name, columns);
  }
  return tables;
}

function valueExpression(table: string, column: string): string {
  const identifier = `${quoteIdentifier(PUBLIC_SCHEMA)}.${quoteIdentifier(table)}.${quoteIdentifier(column)}`;
  return `(CASE WHEN ${identifier} IS NULL THEN 'N:' ELSE 'V:' || length(${identifier}::text)::text || ':' || ${identifier}::text END)`;
}

async function aggregateDatabase(client: Client, runSalt: string): Promise<DatabaseAggregate> {
  const schemas = await listColumns(client);
  const tables: Record<string, TableAggregate> = {};
  let totalRows = 0n;

  for (const [tableName, schema] of schemas) {
    const tableIdentifier = `${quoteIdentifier(PUBLIC_SCHEMA)}.${quoteIdentifier(tableName)}`;
    const expressions = schema.map((column) => {
      const value = valueExpression(tableName, column.name);
      // The salt is generated per verification run and passed as a query parameter. This keeps
      // low-entropy identifiers from becoming reusable per-value hash oracles in the evidence
      // file while still making source/restore comparison deterministic for this run.
      const saltedValue = `md5($1::text || ${value})`;
      const digest = `md5(COALESCE(string_agg(${saltedValue}, ',' ORDER BY ${saltedValue}), ''))`;
      return `${digest} AS ${quoteIdentifier(column.name)}`;
    });
    const result = await client.query<AggregateRow>(
      `SELECT COUNT(*)::text AS "__row_count"${expressions.length ? `, ${expressions.join(", ")}` : ""} FROM ${tableIdentifier}`,
      [runSalt],
    );
    const row = result.rows[0];
    const rowCount = String(row?.__row_count ?? "0");
    totalRows += BigInt(rowCount);
    const columns: Record<string, ColumnAggregate> = {};
    for (const column of schema) {
      const checksum = row?.[column.name];
      if (typeof checksum !== "string" || !/^[a-f0-9]{32}$/i.test(checksum)) {
        throw new RestoreVerificationError(`Could not compute aggregate for ${tableName}.${column.name}.`);
      }
      columns[column.name] = { rowCount, checksum: checksum.toLowerCase() };
    }
    tables[tableName] = { rowCount, columns, schema };
  }

  return { totalRows: totalRows.toString(), tables };
}

function compareAggregates(source: DatabaseAggregate, restored: DatabaseAggregate): string[] {
  const mismatches: string[] = [];
  if (source.totalRows !== restored.totalRows) {
    mismatches.push(`total row count ${source.totalRows} != ${restored.totalRows}`);
  }
  const sourceNames = Object.keys(source.tables).sort();
  const restoredNames = Object.keys(restored.tables).sort();
  for (const table of sourceNames) {
    if (!restored.tables[table]) mismatches.push(`missing restored table ${table}`);
  }
  for (const table of restoredNames) {
    if (!source.tables[table]) mismatches.push(`unexpected restored table ${table}`);
  }
  for (const table of sourceNames) {
    const left = source.tables[table];
    const right = restored.tables[table];
    if (!left || !right) continue;
    if (left.rowCount !== right.rowCount) {
      mismatches.push(`${table} row count ${left.rowCount} != ${right.rowCount}`);
    }
    // PostgreSQL preserves dropped-column attribute numbers on a live table, while pg_dump
    // recreates the restored table and compacts those physical ordinals. Compare the logical
    // contract (name + declared type) rather than that implementation detail.
    const logicalSchema = (schema: TableAggregate["schema"]) =>
      schema.map(({ name, dataType, udtName }) => ({ name, dataType, udtName }));
    if (JSON.stringify(logicalSchema(left.schema)) !== JSON.stringify(logicalSchema(right.schema))) {
      mismatches.push(`${table} schema differs`);
    }
    for (const column of Object.keys(left.columns).sort()) {
      const leftColumn = left.columns[column];
      const rightColumn = right.columns[column];
      if (!rightColumn) {
        mismatches.push(`missing restored column ${table}.${column}`);
        continue;
      }
      if (leftColumn.checksum !== rightColumn.checksum) {
        mismatches.push(`${table}.${column} checksum differs`);
      }
    }
    for (const column of Object.keys(right.columns)) {
      if (!left.columns[column]) mismatches.push(`unexpected restored column ${table}.${column}`);
    }
  }
  return mismatches;
}

function runPsql(
  psqlPath: string,
  targetUrl: string,
  database: string,
  dumpPath: string,
  timeoutMs: number,
): Promise<void> {
  return new Promise((resolve, reject) => {
    const child = spawn(
      psqlPath,
      ["--no-psqlrc", "--no-password", "--dbname", database, "--file", dumpPath, "--set", "ON_ERROR_STOP=1"],
      { env: { ...process.env, ...postgresToolEnv(targetUrl) }, shell: false, windowsHide: true },
    );
    let settled = false;
    const timeout = setTimeout(() => {
      if (settled) return;
      settled = true;
      child.kill();
      reject(new RestoreVerificationError("psql restore exceeded the command timeout."));
    }, timeoutMs);
    timeout.unref();
    child.on("error", () => {
      if (settled) return;
      settled = true;
      clearTimeout(timeout);
      reject(new RestoreVerificationError("Could not start the configured psql executable."));
    });
    child.on("close", (code) => {
      if (settled) return;
      settled = true;
      clearTimeout(timeout);
      if (code === 0) resolve();
      else reject(new RestoreVerificationError(`psql restore failed with exit code ${code ?? "unknown"}.`));
    });
  });
}

function disposableName(): string {
  const stamp = new Date().toISOString().replace(/\D/g, "").slice(0, 14);
  const suffix = randomBytes(5).toString("hex");
  return `mkttool_restore_${stamp}_${suffix}`.slice(0,  sixtyThreeCharacters());
}

function sixtyThreeCharacters(): number {
  // PostgreSQL identifiers are limited to NAMEDATALEN - 1 (63) bytes. All generated characters
  // are ASCII, so a character count is also a byte count.
  return 63;
}

function sameServer(source: DatabaseUrlInfo, target: DatabaseUrlInfo): boolean {
  return source.host === target.host && source.port === target.port;
}

/** Execute a complete disposable restore and return sanitized aggregate evidence. */
export async function verifyDatabaseRestore(
  options: RestoreVerificationOptions,
): Promise<RestoreVerificationReport> {
  const started = new Date();
  const startedMs = Date.now();
  const source = parseDatabaseUrl(options.sourceUrl, "Source URL");
  const target = parseDatabaseUrl(options.targetTemplateUrl, "Target URL");
  const dump = assertDump(options.dumpPath);
  const targetDatabase = disposableName();
  const targetUrl = withDatabase(target, targetDatabase);
  const targetDescription = `${target.host}:${target.port}/${targetDatabase}`;
  let sourceClient: Client | undefined;
  let targetClient: Client | undefined;
  let created = false;
  let cleanup: "PASS" | "FAIL" = "PASS";
  let sourceAggregate: DatabaseAggregate | undefined;
  let restoredAggregate: DatabaseAggregate | undefined;
  let mismatches: string[] = [];
  let error: string | undefined;
  // Never persist this value: it exists only to bind source and restored aggregates within the
  // current invocation and prevents the report from serving as a low-entropy value oracle.
  const runSalt = randomBytes(32).toString("hex");

  try {
    if (sameServer(source, target) && !options.allowSameServer) {
      throw new RestoreVerificationError(
        "Source and target use the same PostgreSQL server; provide a separate restore server or explicitly pass --allow-same-server.",
      );
    }
    sourceClient = createClient(source.url.toString());
    await sourceClient.connect();
    sourceAggregate = await aggregateDatabase(sourceClient, runSalt);
    if (sourceAggregate.totalRows === "0") {
      throw new RestoreVerificationError("Source database contains zero rows; an empty backup cannot close the restore gate.");
    }

    await createDisposableDatabase(target, targetDatabase);
    created = true;
    await runPsql(
      options.psqlPath?.trim() || process.env.PSQL_PATH?.trim() || "psql",
      targetUrl,
      targetDatabase,
      dump.absolutePath,
      options.commandTimeoutMs ?? DEFAULT_COMMAND_TIMEOUT_MS,
    );

    targetClient = createClient(targetUrl);
    await targetClient.connect();
    restoredAggregate = await aggregateDatabase(targetClient, runSalt);
    mismatches = compareAggregates(sourceAggregate, restoredAggregate);
    if (mismatches.length > 0) {
      throw new RestoreVerificationError("Restored aggregates do not match the source database.");
    }
  } catch (caught) {
    error = caught instanceof Error ? caught.message : "Restore verification failed.";
  } finally {
    await closeClient(targetClient);
    await closeClient(sourceClient);
    if (created) {
      try {
        await dropDisposableDatabase(target, targetDatabase);
      } catch {
        cleanup = "FAIL";
      }
    }
  }

  const finished = new Date();
  const report: RestoreVerificationReport = {
    status: !error && mismatches.length === 0 && cleanup === "PASS" ? "PASS" : "FAIL",
    startedAt: started.toISOString(),
    finishedAt: finished.toISOString(),
    durationMs: Date.now() - startedMs,
    source: describeDatabase(source),
    target: targetDescription,
    dump: { path: path.basename(dump.absolutePath), sizeBytes: dump.sizeBytes },
    sourceAggregate,
    restoredAggregate,
    mismatches,
    cleanup,
    ...(error ? { error } : {}),
  };
  return report;
}

/** Write a report atomically, refusing to overwrite a previous receipt. */
export function writeRestoreReport(filePath: string, report: RestoreVerificationReport): void {
  const absolute = path.resolve(filePath);
  mkdirSync(path.dirname(absolute), { recursive: true });
  if (existsSync(absolute)) throw new RestoreVerificationError("Refusing to overwrite an existing restore report.");
  const temporary = `${absolute}.${process.pid}.tmp`;
  const fd = openSync(temporary, "wx", 0o600);
  try {
    writeFileSync(fd, `${JSON.stringify(report, null, 2)}\n`, { encoding: "utf8" });
    fsyncSync(fd);
  } finally {
    closeSync(fd);
  }
  renameSync(temporary, absolute);
}
